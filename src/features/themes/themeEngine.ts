import { z } from 'zod';

export const ALLOWED_PULSE_TOKEN_PREFIXES = [
  '--pulse-color-',
  '--pulse-glass-',
  '--pulse-radius-',
  '--pulse-space-',
  '--pulse-font-',
  '--pulse-blur-',
  '--pulse-motion-',
  '--pulse-sidebar-',
  '--pulse-playerbar-',
  '--pulse-art-',
  '--pulse-ui-',
  '--pulse-shadow-',
] as const;

export const SURFACE_STYLES = ['glass', 'aero', 'matte', 'minimal', 'brutalist'] as const;
export type SurfaceStyle = (typeof SURFACE_STYLES)[number];

export const SHELL_LAYOUTS = ['split', 'bottom-player', 'zen-stage'] as const;
export type ShellLayout = (typeof SHELL_LAYOUTS)[number];

export const ARTWORK_STYLES = ['rounded', 'sharp', 'vinyl', 'minimal'] as const;
export type ArtworkStyle = (typeof ARTWORK_STYLES)[number];

export const FONT_PRESETS = ['sans', 'mono', 'serif', 'geometric'] as const;
export type FontPreset = (typeof FONT_PRESETS)[number];

export const BACKDROP_TEXTURES = ['none', 'bubbles', 'noise', 'grid', 'scanlines'] as const;
export type BackdropTexture = (typeof BACKDROP_TEXTURES)[number];

export const WINDOW_CHROME_STYLES = ['macos', 'minimal', 'hidden'] as const;
export type WindowChromeStyle = (typeof WINDOW_CHROME_STYLES)[number];

export const THEME_CATEGORIES = [
  'aero',
  'matte',
  'terminal',
  'brutalist',
  'minimal',
  'glass',
] as const;
export type ThemeCategory = (typeof THEME_CATEGORIES)[number];

export function isSafeTokenKey(key: string): boolean {
  return ALLOWED_PULSE_TOKEN_PREFIXES.some((prefix) => key.startsWith(prefix));
}

export function isSafeCssTokenValue(value: string): boolean {
  const trimmed = value.trim();
  if (trimmed.length === 0 || trimmed.length > 160) {
    return false;
  }
  // Reject CSS injection / external network loads in theme JSON packs
  const forbidden = /[;{}<>]|url\s*\(|javascript:|expression\s*\(/i;
  return !forbidden.test(trimmed);
}

export const ThemePackSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9][a-z0-9-]{1,62}$/),
    name: z.string().min(1).max(80),
    description: z.string().max(180).optional(),
    author: z.string().min(1).max(80).default('User'),
    mode: z.enum(['dark', 'light']),
    category: z.enum(THEME_CATEGORIES).optional(),
    surfaceStyle: z.enum(SURFACE_STYLES).optional(),
    artworkStyle: z.enum(ARTWORK_STYLES).optional(),
    fontPreset: z.enum(FONT_PRESETS).optional(),
    backdropTexture: z.enum(BACKDROP_TEXTURES).optional(),
    ambientGlow: z.boolean().optional(),
    tokens: z.record(z.string(), z.string()),
  })
  .superRefine((theme, ctx) => {
    for (const [key, val] of Object.entries(theme.tokens)) {
      if (!isSafeTokenKey(key)) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: `Disallowed token key "${key}". Themes may only target --pulse-* tokens.`,
        });
      }
      if (!isSafeCssTokenValue(val)) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: `Unsafe CSS token value for "${key}".`,
        });
      }
    }
  });

export type ThemePack = z.infer<typeof ThemePackSchema>;

